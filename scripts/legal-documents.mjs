import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { compileSource } from './source-test-loader.mjs';

const root = path.resolve(import.meta.dirname, '..');
const directory = await mkdtemp(path.join(tmpdir(), 'fabelpad-legal-'));
const check = process.argv.includes('--check');
if (!check && !process.argv.includes('--write')) throw new Error('Gebruik --check of --write. Een bestaande aanvaarde documentversie mag niet worden overschreven.');
try {
  const { terms } = await import(await compileSource(new URL('../src/legalContent.ts', import.meta.url), directory));
  const { privacy } = await import(await compileSource(new URL('../src/privacyContent.ts', import.meta.url), directory));
  const version = '2026-11-22';
  const entries = [['terms', 'algemene-voorwaarden.md', terms], ['privacy', 'privacyverklaring.md', privacy]];
  const catalog = {};
  const outputs = [];
  for (const [key, filename, document] of entries) {
    if (document.version !== version) throw new Error('Werk de catalogus en downloadmap bij voor een nieuwe documentversie.');
    const blocks = [`# ${document.title}`, `Versie: ${document.version}\nIngangsdatum: ${document.updated}`, document.introduction, 'Aanbieder: DG Webservices\nVestigingsplaats: Den Haag (\'S-Gravenhage)\nKVK-nummer: 88135713\nAlgemeen contact: info@dgwebservices.nl\nWebsite: https://www.dgwebservices.nl\nFabelpad-support en privacy: support@fabelpad.nl\nBedrijfsgegevens: https://fabelpad.nl/bedrijfsgegevens'];
    for (const section of document.sections) blocks.push(`## ${section.title}`, ...section.paragraphs);
    if (key === 'privacy') blocks.push('## Privacyinformatie van dienstverleners', '- Supabase DPA: https://supabase.com/legal/customer-resources/data-processing-addendum\n- Supabase subverwerkers: https://supabase.com/legal/subprocessors\n- Resend DPA: https://resend.com/legal/dpa\n- Resend subverwerkers: https://resend.com/legal/subprocessors\n- Google: https://policies.google.com/privacy?hl=nl');
    const text = `${blocks.join('\n\n')}\n`;
    const sha256 = createHash('sha256').update(text).digest('hex');
    catalog[key] = { version: document.version, filename, sha256 };
    outputs.push([`public/legal/${version}/${filename}`, text]);
  }
  outputs.push([`public/legal/${version}/manifest.json`, `${JSON.stringify(catalog, null, 2)}\n`]);
  outputs.push(['lib/legal/documentHashes.ts', `/** SHA-256 of the exact UTF-8 downloads. Generated by scripts/legal-documents.mjs. */\nexport const LEGAL_DOCUMENT_HASHES = ${JSON.stringify(Object.fromEntries(Object.entries(catalog).map(([key, value]) => [key, value.sha256])), null, 2)} as const;\n`]);
  outputs.push([`public/legal/${version}/herroepingsformulier.txt`, 'Aan DG Webservices, via support@fabelpad.nl\n\nIk laat hierbij weten dat ik mijn overeenkomst voor het volgende Fabelpad-abonnement herroep.\n\nAbonnement en eventueel bestelnummer:\nDatum waarop ik het abonnement afsloot:\nNaam van de accounthouder:\nAdres van de accounthouder:\nE-mailadres waarmee ik heb besteld:\nDatum van dit bericht:\nHandtekening, alleen als dit formulier op papier wordt verstuurd:\n']);
  for (const [filename, body] of outputs) {
    const target = path.join(root, filename);
    if (check) {
      let actual;
      try { actual = await readFile(target, 'utf8'); } catch { throw new Error(`Versiegebonden juridisch bestand ontbreekt: ${filename}`); }
      if (actual !== body) throw new Error(`Juridische weergave en download verschillen: ${filename}. Maak een nieuwe versie als de aangeboden tekst al is aanvaard.`);
    } else { await mkdir(path.dirname(target), { recursive: true }); await writeFile(target, body); }
  }
  console.log(`Juridische documenten ${check ? 'gecontroleerd' : 'gegenereerd'}: 2 documenten, exacte UTF-8-hashes en herroepingsmodel; versie ${version}.`);
} finally { await rm(directory, { recursive: true, force: true }); }
